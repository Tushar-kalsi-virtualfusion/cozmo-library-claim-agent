import Foundation
import simd

@main struct CapturePolicyChecks {
    static func main() {
        precondition(CaptureModePolicy.preferred(lidarSupported:true) == .lidar)
        precondition(CaptureModePolicy.preferred(lidarSupported:false) == .camera)
        precondition(!CaptureModePolicy.accepts("camera",lidarSupported:true))
        precondition(!CaptureModePolicy.accepts("lidar",lidarSupported:false))
        precondition(CaptureModePolicy.accepts("comparison",lidarSupported:true))
        precondition(!CaptureModePolicy.accepts("comparison",lidarSupported:false))

        var gate = LocalSetupGate()
        gate.seedCaptureMode("lidar")
        precondition(gate.phase == "collecting")
        precondition(gate.preferences["capture_mode"] == .string("lidar"))
        let details: JSONValue = .object(["language":.string("English"),"country":.string("India"),"currency":.string("INR")])
        guard case .readback(let setup) = gate.next(intent:"ready",proposal:details) else { preconditionFailure("Ready cannot replace setup readback") }
        precondition(setup["capture_mode"] == .string("lidar"))
        precondition(gate.next(intent:"confirm",proposal:.null) == .readback(setup))
        gate.readbackDelivered()
        let conflict: JSONValue = .object(["capture_mode":.string("camera")])
        precondition(gate.next(intent:"confirm",proposal:conflict) == .readback(setup))
        precondition(gate.phase == "readback", "An inconsistent confirmation cannot configure capture")
        gate.readbackDelivered()
        precondition(gate.next(intent:"confirm",proposal:.null) == .configure(setup))
        gate.configured()
        precondition(gate.next(intent:"ready",proposal:.null) == .askReadiness)
        gate.readinessDelivered()
        precondition(gate.next(intent:"ready",proposal:.null) == .requestCapture)

        var restored = LocalSetupGate()
        restored.seedCaptureMode("camera")
        guard case .object(var saved) = setup else { preconditionFailure("Expected setup fields") }
        saved["confirmed"] = .bool(true)
        restored.restore(.object(saved))
        precondition(restored.phase == "collecting", "Unsupported saved mode cannot restore consent")
        precondition(restored.preferences["capture_mode"] == .string("camera"))
        restored.seedCaptureMode("")
        precondition(restored.preferences["capture_mode"] == .string("camera"))

        var uploads = LiveGeometryUploadGate()
        let a = Data("old live".utf8), b = Data("new live".utf8), c = Data("latest live".utf8)
        uploads.reset(sessionID:"one")
        uploads.offer(a,sessionID:"one")
        precondition(uploads.next() == nil, "Local saved frames do not establish server session identity")
        uploads.frameAccepted(sessionID:"other")
        precondition(uploads.next() == nil)
        uploads.frameAccepted(sessionID:"one")
        precondition(uploads.next() == a)
        uploads.offer(b,sessionID:"one")
        uploads.offer(c,sessionID:"one")
        precondition(uploads.next() == nil, "Only one live upload can be in flight")
        uploads.completed(a,sessionID:"one",succeeded:false)
        precondition(uploads.next() == c, "A failed older upload must not overwrite the latest geometry")
        uploads.offer(b,sessionID:"one")
        uploads.beginFinalization()
        uploads.completed(c,sessionID:"one",succeeded:true)
        uploads.offer(a,sessionID:"one")
        precondition(uploads.next() == nil, "No queued live geometry can overwrite final geometry")
        uploads.reset(sessionID:"two")
        uploads.completed(c,sessionID:"one",succeeded:false)
        uploads.frameAccepted(sessionID:"one")
        uploads.offer(a,sessionID:"one")
        precondition(uploads.next() == nil, "An earlier sweep cannot publish into the next sweep")
        uploads.offer(b,sessionID:"two")
        uploads.frameAccepted(sessionID:"two")
        precondition(uploads.next() == b)
        uploads.completed(b,sessionID:"two",succeeded:false)
        precondition(uploads.next() == b, "Failed upload remains available for a later retry")

        let polygon: [SIMD3<Float>] = [SIMD3(0,0,0),SIMD3(3,0,0),SIMD3(3,1,0),SIMD3(2,1,0),SIMD3(2,3,0),SIMD3(0,3,0)]
        let transform = simd_float4x4(columns:(SIMD4(1,0,0,0),SIMD4(0,0,1,0),SIMD4(0,-1,0,0),SIMD4(2,0,5,1)))
        precondition(RoomSurfaceGeometry.floorCorners(polygon,transform:transform,final:false) == nil)
        precondition(RoomSurfaceGeometry.floorCorners([],transform:transform,final:true) == nil)
        precondition(RoomSurfaceGeometry.floorCorners(polygon,transform:transform,final:true) == [[2,0,5],[5,0,5],[5,0,6],[4,0,6],[4,0,8],[2,0,8]])
        precondition(RoomSurfaceGeometry.floorCorners([SIMD3(.nan,0,0),SIMD3(1,0,0),SIMD3(1,1,0)],transform:transform,final:true) == nil)
        print("Capture policy, separate consent, final floor polygon and coalesced geometry ordering checks passed")
    }
}
